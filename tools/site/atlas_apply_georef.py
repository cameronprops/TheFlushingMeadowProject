#!/usr/bin/env python3
"""Turn Fairground Atlas raster traces into uncertified PROJECTED_PREVIEW coordinates.

Requires a fit generated by tools/georeferencing/fmp_georef.py with
>=3 controls, >=2 independent holdout points. Writes a NEW CSV file only.
Never auto-approves world placement or edits the master catalog in place.
"""
import argparse,csv,json,math
from pathlib import Path

def convert(fit,rows,map_id,max_holdout_m=10.0):
    if fit.get('certified') is not False or fit.get('coordinate_units')!='metres':
        raise ValueError('Require uncertified metric FMP fit')
    if fit.get('crs') not in ('EPSG:32118','EPSG:26918'):
        raise ValueError('Require a supported metre-based site CRS')
    if not all(isinstance(fit.get(k),(int,float)) and math.isfinite(fit[k])
               for k in ('control_rmse_m','check_rmse_m')):
        raise ValueError('Missing independent holdout/control residuals')
    if fit['check_rmse_m'] > max_holdout_m:
        raise ValueError('Poor holdout fit; recheck historical map control')
    tx,ty=fit['affine_x'],fit['affine_y']
    if len(tx)!=3 or len(ty)!=3 or not all(isinstance(v,(int,float)) and math.isfinite(v) for v in tx+ty):
        raise ValueError('Invalid affine')
    updated=[]
    for r in rows:
        row=dict(r)
        if row.get('source_map_id')!=map_id:
            updated.append(row);continue
        if row.get('placement_status')!='RASTER_TRACE':
            raise ValueError('Expected source pixel trace: '+row['placement_id'])
        points=json.loads(row.get('pixel_vertices_json') or 'null')
        if not isinstance(points,list) or not points:
            raise ValueError('Missing pixel vertices: '+row['placement_id'])
        projected=[]
        for px,py in points:
            if not math.isfinite(px) or not math.isfinite(py):
                raise ValueError('Nonfinite source pixel point')
            projected.append([round(tx[0]*px+tx[1]*py+tx[2],5),
                              round(ty[0]*px+ty[1]*py+ty[2],5)])
        row['projected_vertices_json']=json.dumps(projected,separators=(',',':'))
        row['placement_status']='PROJECTED_PREVIEW'
        row['uncertainty_m']=str(max(fit['check_rmse_m'],fit['control_rmse_m']))
        row['note']=((row.get('note') or '')+' | Projected PREVIEW; '+fit['crs']+
                     ' holdout RMSE '+str(fit['check_rmse_m'])+'m').strip()
        updated.append(row)
    return updated

if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('csv')
    ap.add_argument('--fit',required=True)
    ap.add_argument('--map-id',required=True)
    ap.add_argument('--output',required=True)
    ap.add_argument('--max-holdout-m',type=float,default=10.)
    args=ap.parse_args()
    fit=json.loads(Path(args.fit).read_text(encoding='utf-8'))
    with Path(args.csv).open(newline='',encoding='utf-8') as f:
        reader=csv.DictReader(f)
        header=reader.fieldnames or [];records=list(reader)
    done=convert(fit,records,args.map_id,args.max_holdout_m)
    with Path(args.output).open('w',newline='',encoding='utf-8') as f:
        w=csv.DictWriter(f,fieldnames=header);w.writeheader();w.writerows(done)
    print('Projected PREVIEW:',sum(r['placement_status']=='PROJECTED_PREVIEW' for r in done))
